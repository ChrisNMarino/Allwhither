#!/usr/bin/env python3
"""Embed project .json and .js files as obfuscated bytes.

The transform is symmetric XOR obfuscation, not encryption. A reader with the
binary can still recover the bytes. It keeps the project files out of the
build directory and out of a plain `strings` dump.

KEY must match platform/web/resource-codec.js. Native decoders read the key
from the generated source, which this script emits.
"""

import argparse
import base64
import html
import json
import sys
from pathlib import Path

KEY = bytes((
    0x6F, 0xA3, 0x19, 0xC4, 0x57, 0xE8, 0x2B, 0x91,
    0xD0, 0x44, 0x7E, 0x13, 0xB6, 0x08, 0xF5, 0x6A,
))
EXTENSIONS = {".json", ".js"}


def obfuscate(data: bytes) -> bytes:
    output = bytearray(len(data))
    for index, value in enumerate(data):
        mask = KEY[index % len(KEY)] ^ ((index * 13 + 7) & 0xFF)
        output[index] = value ^ mask
    return bytes(output)


def collect(project_dir: Path) -> list[tuple[str, bytes]]:
    root = project_dir.resolve()
    if not root.is_dir():
        raise SystemExit(f"Project directory does not exist: {project_dir}")
    found = []
    for path in root.rglob("*"):
        if not path.is_file() or path.is_symlink():
            continue
        if path.suffix.lower() not in EXTENSIONS:
            continue
        resolved = path.resolve()
        if root != resolved and root not in resolved.parents:
            continue
        found.append((path.relative_to(root).as_posix(), resolved.read_bytes()))
    if not any(name.endswith(".json") for name, _contents in found):
        raise SystemExit(f"No .json file found in {project_dir}")
    found.sort(key=lambda item: item[0])
    return found


def quote(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def format_hex(data: bytes, indent: str, per_line: int = 12) -> str:
    if not data:
        return ""
    lines = []
    for start in range(0, len(data), per_line):
        chunk = ", ".join(f"0x{byte:02x}" for byte in data[start:start + per_line])
        lines.append(f"{indent}{chunk}")
    return ",\n".join(lines)


def kotlin_literal(value: int) -> str:
    if value > 127:
        return f"0x{value:02x}.toByte()"
    return f"0x{value:02x}"


def format_kotlin(data: bytes, indent: str, per_line: int = 12) -> str:
    if not data:
        return ""
    lines = []
    for start in range(0, len(data), per_line):
        chunk = ", ".join(kotlin_literal(byte) for byte in data[start:start + per_line])
        lines.append(f"{indent}{chunk}")
    return ",\n".join(lines)


def emit_c(files: list[tuple[str, bytes]]) -> str:
    parts = [
        "/* Generated by tools/embed_resources.py. Do not edit. */\n",
        '#include "embedded_resources.h"\n\n',
        "const unsigned char allwhither_embedded_key[16] = {\n",
        format_hex(KEY, "    "),
        "\n};\n\n",
    ]
    entries = []
    for index, (name, contents) in enumerate(files):
        encoded = obfuscate(contents)
        symbol = f"allwhither_resource_{index}"
        if encoded:
            parts.append(f"static const unsigned char {symbol}[] = {{\n")
            parts.append(format_hex(encoded, "    "))
            parts.append("\n};\n\n")
            entries.append(
                f'    {{ {quote(name)}, {symbol}, sizeof {symbol} }}')
        else:
            parts.append(f"static const unsigned char {symbol}[1] = {{ 0 }};\n\n")
            entries.append(f'    {{ {quote(name)}, {symbol}, 0 }}')
    parts.append("const AllwhitherEmbeddedResource allwhither_embedded_resources[] = {\n")
    parts.append(",\n".join(entries))
    parts.append(",\n    { NULL, NULL, 0 }\n};\n")
    return "".join(parts)


def emit_csharp(files: list[tuple[str, bytes]], project_name: str) -> str:
    parts = [
        "// Generated by tools/embed_resources.py. Do not edit.\n",
        "using System.Collections.Generic;\n\n",
        "namespace Allwhither.Windows;\n\n",
        "internal static class EmbeddedResourceData\n{\n",
        f"    internal const string ProjectName = {quote(project_name)};\n\n",
        "    internal static readonly byte[] Key = new byte[]\n    {\n",
        format_hex(KEY, "        "),
        "\n    };\n\n",
        "    internal static readonly Dictionary<string, byte[]> Files =\n",
        "        new Dictionary<string, byte[]>(System.StringComparer.Ordinal)\n        {\n",
    ]
    for name, contents in files:
        encoded = obfuscate(contents)
        parts.append(f"            [{quote(name)}] = new byte[]\n")
        if encoded:
            parts.append("            {\n")
            parts.append(format_hex(encoded, "                "))
            parts.append("\n            },\n")
        else:
            parts.append("            { },\n")
    parts.append("        };\n}\n")
    return "".join(parts)


def emit_kotlin(files: list[tuple[str, bytes]]) -> str:
    parts = [
        "// Generated by tools/embed_resources.py. Do not edit.\n",
        "package org.allwhither.starter\n\n",
        "import android.util.Base64\n\n",
        "internal object EmbeddedResourceData {\n",
        "    val key: ByteArray = byteArrayOf(\n",
        format_kotlin(KEY, "        "),
        "\n    )\n\n",
        "    val files: Map<String, ByteArray> by lazy {\n",
        "        mapOf(\n",
    ]
    for name, contents in files:
        encoded = obfuscate(contents)
        b64 = base64.b64encode(encoded).decode("ascii")
        parts.append(
            f"            {quote(name)} to Base64.decode({quote(b64)}, Base64.DEFAULT),\n"
        )
    parts.append("        )\n    }\n}\n")
    return "".join(parts)


def emit_json(files: list[tuple[str, bytes]], project_name: str) -> str:
    entry = f"{project_name}.json"
    if not any(name == entry for name, _contents in files):
        raise SystemExit(f"Missing entry file {entry}")
    payload = {
        "entry": entry,
        "files": {
            name: base64.b64encode(obfuscate(contents)).decode("ascii")
            for name, contents in files
        },
    }
    return json.dumps(payload, separators=(",", ":"))


def emit_android_resource(files: list[tuple[str, bytes]], project_name: str) -> str:
    entry = f"{project_name}.json"
    contents = {name: data for name, data in files}
    if entry not in contents:
        raise SystemExit(f"Missing entry file {entry}")

    def load(path: str, stack: set[str]) -> dict:
        normalized = path.replace("\\", "/").strip("/")
        if normalized in stack:
            raise SystemExit(f"Configuration include cycle at: {normalized}")
        if normalized not in contents:
            raise SystemExit(f"Missing included .json file: {normalized}")
        config = json.loads(contents[normalized].decode("utf-8"))
        merged = {}
        for include in config.get("includes", []):
            include = str(include).replace("\\", "/")
            parent = normalized.rpartition("/")[0]
            include_path = f"{parent}/{include}" if parent else include
            parts = []
            for segment in include_path.split("/"):
                if segment in ("", "."):
                    continue
                if segment == "..":
                    if not parts:
                        raise SystemExit(
                            f"Include path escapes the project: {include_path}")
                    parts.pop()
                else:
                    parts.append(segment)
            included = load("/".join(parts), stack | {normalized})
            merged.update(included)
        merged.update({key: value for key, value in config.items()
                       if key != "includes"})
        return merged

    application = load(entry, set()).get("application")
    if not isinstance(application, dict):
        raise SystemExit(f"{entry} must contain an application object.")
    name = application.get("name")
    if not isinstance(name, str) or not name.strip():
        raise SystemExit(f"{entry} application.name must be a non-empty string.")
    escaped = html.escape(name.strip(), quote=True)
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<resources>\n"
        f'    <string name="app_name">{escaped}</string>\n'
        "</resources>\n"
    )


def self_test() -> None:
    sample = b'{"title":"Hello World","id":"org.allwhither.example"}'
    encoded = obfuscate(sample)
    if obfuscate(encoded) != sample:
        raise SystemExit("obfuscation is not symmetric")
    if sample in encoded or b"Hello World" in encoded or b"org.allwhither.example" in encoded:
        raise SystemExit("plaintext survived obfuscation")
    print("embed_resources self-test passed")


def main() -> None:
    if "--self-test" in sys.argv:
        self_test()
        return

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--platform", required=True,
        choices=("c", "csharp", "kotlin", "json", "android"))
    parser.add_argument("--project-dir", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    files = collect(args.project_dir)
    project_name = args.project_dir.resolve().name
    emitters = {
        "c": lambda: emit_c(files),
        "csharp": lambda: emit_csharp(files, project_name),
        "kotlin": lambda: emit_kotlin(files),
        "json": lambda: emit_json(files, project_name),
        "android": lambda: emit_android_resource(files, project_name),
    }
    rendered = emitters[args.platform]()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")


if __name__ == "__main__":
    main()
